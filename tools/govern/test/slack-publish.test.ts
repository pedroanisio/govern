// Publishing a routed reply (SLACK.md): a reply to a routed Slack request whose content check passed is offered to the
// configured publishers in a review channel, never to the requester's channel. A publisher's signed click records an
// approval; `govern slack listen` (the inbox's one writer) then posts the reply once, keyed, in the request's thread,
// after checking again that it is the same verified text. Unverified, unchecked and BLOCKED replies are never offered.
import { test } from "node:test";
import assert from "node:assert/strict";
import { createHmac } from "node:crypto";
import { createServer } from "node:http";
import { join } from "node:path";
import { readFileSync, writeFileSync } from "node:fs";
import { makeEnv, childEnv, setConfig, write, jsonl, type Env } from "./helpers.ts";
import * as queue from "../lib/queue.ts";
import { handleInteraction } from "../ext/slack/slack.ts";
import { notify } from "../ext/slack/notify.ts";
import { publishApproved } from "../ext/slack/publish.ts";
import type { Call as SlackCall } from "../ext/slack/channel.ts";

const SECRET = "signing-secret-with-32-characters", NOW = Math.floor(Date.now() / 1000), REQUEST = "1793000000.000100";
const CONFIG = { team: "T1", channel: "C1", inbox: "generated/slack", bot: ["UBOT"], requesters: { U1: "operator" }, tags: ["request"],
  route: { to: "codex", profile: "codex-read", maxPerHour: 5, publishers: ["U0PUB"], review: "C0REV" } };

type Button = { action_id: string; value: string; text: { text: string } };
type Block = { type: string; block_id?: string; elements?: Button[]; text?: { text: string } };
interface Call { method: string; body: Record<string, unknown> }

async function workspace(f: (e: Env, d: string, api: string, calls: Call[]) => Promise<void>, slack: Record<string, unknown> = CONFIG): Promise<void> {
  const e = makeEnv("slack-publish"), before = process.env, d = join(e.root, "generated/slack");
  setConfig(e, { slack }); process.env = childEnv(e);
  const calls: Call[] = []; let ts = 0;
  const server = createServer((req, res) => {
    let body = ""; req.on("data", (c) => { body += c; });
    req.on("end", () => { const b = JSON.parse(body); calls.push({ method: (req.url ?? "").replace(/^\/api\//, ""), body: b });
      res.writeHead(200, { "Content-Type": "application/json" });
      res.end(JSON.stringify({ ok: true, channel: b.channel, ts: b.ts ?? `1793000001.${String(++ts).padStart(6, "0")}` })); });
  });
  await new Promise<void>((r) => server.listen(0, "127.0.0.1", r));
  try {
    write(join(d, "start-line.json"), JSON.stringify({ ts: "0" }));
    write(join(d, "inbox.jsonl"), JSON.stringify({ ts: REQUEST, thread_ts: null, user: "U1", text: "[request] where is the SLA report?" }) + "\n");
    await f(e, d, `http://127.0.0.1:${(server.address() as { port: number }).port}/api`, calls);
  } finally { process.env = before; server.closeAllConnections(); await new Promise<void>((r) => server.close(() => r())); }
}

/** A routed task for the request and a reply to it, with the content check's verdict `state` (none: no check ran). */
function routed(d: string, o: { kind?: string; state?: "checked" | "unverified" | "shape only"; body?: string; ts?: string } = {}): queue.Message {
  const task = queue.send({ project: "slack", task: `slack-${o.ts ?? "a"}`, kind: "TASK", from: "owner", to: "codex", summary: "Slack request", body: "quoted", files: [], access: "read-only" });
  const routes = (() => { try { return JSON.parse(readFileSync(join(d, "routes.json"), "utf8")); } catch { return {}; } })();
  routes[o.ts ?? REQUEST] = { task: task.id, at: new Date().toISOString() };
  write(join(d, "routes.json"), JSON.stringify(routes));
  const reply = queue.send({ project: "slack", task: task.task, kind: o.kind ?? "REVIEW", from: "codex", to: "owner", summary: "The SLA report",
    body: o.body ?? "The SLA report is generated by report/build.py:12 and saved under generated/report.pdf.", files: [], replyTo: task.id, access: "read-only" });
  if (o.state !== undefined) setVerification(reply.id, o.state);
  return queue.find(reply.id)!.m;
}
function setVerification(id: string, state: "checked" | "unverified" | "shape only", body?: string): void {
  const at = queue.find(id)!, file = join(queue.QUEUE(), at.state, `${id}.json`);
  writeFileSync(file, JSON.stringify({ ...at.m, ...(body ? { body } : {}), verification: { state, reason: state === "checked" ? "file-refs passed" : "no file:line" } }));
}
const run = (api: string) => notify({ api, token: "xoxb-t", channel: "C1" });
const buttons = (c: Call) => ((c.body.blocks as Block[] | undefined) ?? []).filter((b) => b.type === "actions").flatMap((b) => b.elements ?? []);
const reviews = (calls: Call[]) => calls.filter((c) => c.method === "chat.postMessage" && c.body.channel === "C0REV");
async function click(post: Call, user: string, nonce = "1") {
  const b = buttons(post)[0]!;
  const body = Buffer.from("payload=" + encodeURIComponent(JSON.stringify({ type: "block_actions", team: { id: "T1" }, user: { id: user },
    response_url: "https://hooks.slack.com/actions/T1/x", message: post.body, actions: [{ ...b, action_ts: nonce }] })));
  const signature = "v0=" + createHmac("sha256", SECRET).update(`v0:${NOW}:`).update(body).digest("hex"), sent: Record<string, unknown>[] = [];
  const request = (async (_: unknown, init: RequestInit) => { sent.push(JSON.parse(String(init.body))); return new Response("ok"); }) as typeof fetch;
  return { result: await handleInteraction(SECRET, body, String(NOW), signature, { now: () => NOW, request }), sent };
}
const slackApi = (calls: Call[]): SlackCall => async (method, body) => { calls.push({ method, body }); return { ok: true, ts: "1793000002.000001", channel: "C1" }; };

test("a checked reply is offered once to the review channel, in full, with Publish to thread", async () => workspace(async (_e, d, api, calls) => {
  const reply = routed(d, { state: "checked" });
  await run(api); await run(api);
  const offered = reviews(calls);
  assert.equal(offered.length, 1, "offered once");
  assert.match(JSON.stringify(offered[0]!.body.blocks), /report\/build\.py:12/);
  assert.match(JSON.stringify(offered[0]!.body.blocks), new RegExp(reply.id));
  assert.deepEqual(buttons(offered[0]!).map((b) => [b.action_id, b.text.text]), [["govern.publish", "Publish to thread"]]);
  assert.ok(!calls.some((c) => c.body.channel === "C1" && /SLA report is generated/.test(JSON.stringify(c.body))), "nothing in the requester's channel");
}));

test("unverified, unchecked and BLOCKED replies are never offered", async () => workspace(async (_e, d, api, calls) => {
  routed(d, { state: "unverified", ts: "1793000000.000101" });
  routed(d, { state: "shape only", ts: "1793000000.000102" });
  routed(d, { ts: "1793000000.000103" });
  routed(d, { state: "checked", kind: "BLOCKED", ts: "1793000000.000104" });
  await run(api);
  assert.equal(reviews(calls).length, 0);
}));

test("without publishers and a review channel nothing is offered", async () => workspace(async (_e, d, api, calls) => {
  routed(d, { state: "checked" });
  await run(api);
  assert.equal(reviews(calls).length, 0);
}, { ...CONFIG, route: { to: "codex", profile: "codex-read", maxPerHour: 5 } }));

test("a publisher's click records the approval with the signed source and closes the offer; it posts nothing itself", async () => workspace(async (_e, d, api, calls) => {
  const reply = routed(d, { state: "checked" });
  await run(api);
  const before = calls.length, { result, sent } = await click(reviews(calls)[0]!, "U0PUB");
  assert.equal(result.status, 200, JSON.stringify(result.value));
  const approval = JSON.parse(readFileSync(join(d, "publish.json"), "utf8"))[reply.id];
  assert.equal(approval.by, "U0PUB"); assert.equal(approval.source.kind, "slack"); assert.match(approval.digest, /^[0-9a-f]{64}$/);
  assert.equal(calls.length, before, "the decision server does not post to Slack");
  assert.ok(!(sent[0]!.blocks as Block[]).some((b) => b.type === "actions"));
  assert.match(JSON.stringify(sent[0]!.blocks), /Approved by <@U0PUB>/);
  assert.equal((await click(reviews(calls)[0]!, "U0PUB")).result.status, 401, "the same signed click is a replay");
}));

test("someone not a publisher, a reply changed since the offer, or one no longer checked is refused", async () => workspace(async (_e, d, api, calls) => {
  const reply = routed(d, { state: "checked" });
  await run(api);
  const offer = reviews(calls)[0]!;
  assert.equal((await click(offer, "U1")).result.status, 403);
  setVerification(reply.id, "checked", "Something else entirely, see a.ts:1.");
  assert.equal((await click(offer, "U0PUB", "2")).result.status, 409, "the text changed");
  setVerification(reply.id, "unverified", reply.body);
  assert.equal((await click(offer, "U0PUB", "3")).result.status, 409, "no longer checked");
  assert.throws(() => readFileSync(join(d, "publish.json")), /ENOENT/);
}));

test("listen posts an approved reply once in the request's thread, keyed; notify then marks the offer published", async () => workspace(async (_e, d, api, calls) => {
  const reply = routed(d, { state: "checked" });
  await run(api);
  const offer = reviews(calls)[0]!;
  await click(offer, "U0PUB");
  const posted: Call[] = [];
  assert.deepEqual(await publishApproved(slackApi(posted), d, "C1"), [reply.id]);
  assert.equal(posted.length, 1);
  assert.equal(posted[0]!.body.channel, "C1"); assert.equal(posted[0]!.body.thread_ts, REQUEST);
  assert.equal(posted[0]!.body.text, `delivered: ${reply.body}`);
  assert.deepEqual(await publishApproved(slackApi(posted), d, "C1"), [], "never twice");
  assert.equal(posted.length, 1);
  assert.ok(jsonl(join(d, "sent.jsonl")).some((r) => r.key === `publish:${reply.id}`));
  await run(api);
  const closed = calls.find((c) => c.method === "chat.update" && c.body.channel === "C0REV")!;
  assert.ok(closed, "the offer is updated"); assert.equal(buttons(closed).length, 0);
  assert.match(JSON.stringify(closed.body.blocks), /Published to the thread/);
}));

test("an approved reply that is no longer the checked text is not posted", async () => workspace(async (_e, d, api, calls) => {
  const reply = routed(d, { state: "checked" });
  await run(api);
  await click(reviews(calls)[0]!, "U0PUB");
  setVerification(reply.id, "unverified", reply.body);
  const posted: Call[] = [];
  assert.deepEqual(await publishApproved(slackApi(posted), d, "C1"), []);
  assert.equal(posted.length, 0);
}));
